"""
Builds lib/sbi_rates.js from rates.json (collected from officialforexrates.com, which archives the SBI daily
"to be used as reference rates" from 01-01-2022).

    python3 tools/build_rates.py <rates.json> [more.json …]   (files are merged)

rates.json: { "YYYY-MM-DD": {"USD": [tt_buy, tt_sell, bill_buy, bill_sell], ...} | null }
A rate of 0 means none was published for that column on that date.
"""
import json
import os
import sys

src = {}
for f in sys.argv[1:]:
    src.update(json.load(open(f)))
CUR = ["USD", "EUR", "GBP", "JPY"]
data = {}
for d in sorted(src):
    v = src[d]
    if v is None:
        data[d] = 0
        continue
    row = []
    for c in CUR:
        x = v.get(c) or [None] * 4
        row.append([(None if (y is None or y == 0) else y) for y in x])
    data[d] = row
out = {"asOf": max(src), "from": min(src), "cur": CUR, "cols": ["tt_buy", "tt_sell", "bill_buy", "bill_sell"],
       "source": "officialforexrates.com – archive of the SBI daily forex rates (\"to be used as reference rates\")", "data": data}
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "sbi_rates.js")
with open(p, "w") as fh:
    fh.write("// Generated by tools/build_rates.py – SBI TT rates archive. Do not edit by hand.\n")
    fh.write("window.SBI_RATES = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("Written", os.path.abspath(p), len(data), "dates up to", out["asOf"])
