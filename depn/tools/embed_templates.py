"""
Packs the depreciation templates into lib/templates.js so that index.html works when opened
directly from disk (double-click), without a web server.

Run this again whenever you edit a template in the templates folder:
    python3 tools/embed_templates.py
"""
import base64, os, json

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
tdir = os.path.join(ROOT, "templates")
out = {}
for f in sorted(os.listdir(tdir)):
    if f.endswith((".docx", ".xlsx")):
        with open(os.path.join(tdir, f), "rb") as fh:
            out[f.rsplit(".", 1)[0]] = base64.b64encode(fh.read()).decode()
logo = os.path.join(tdir, "logo.png")
if os.path.exists(logo):
    with open(logo, "rb") as fh:
        out["logo_png"] = base64.b64encode(fh.read()).decode()
with open(os.path.join(ROOT, "lib", "templates.js"), "w") as fh:
    fh.write("// Generated by tools/embed_templates.py - do not edit by hand.\n")
    fh.write("window.LLP_TEMPLATES = " + json.dumps(out, indent=1) + ";\n")
print("Embedded:", ", ".join(out))
